#!/usr/bin/env node
// Stable, reviewed primary-source facts for /oracle/research/. Financials are loaded
// directly from the existing validated /oracle/data/financials.js at page load.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './paths.mjs';

const read = (p) => JSON.parse(readFileSync(join(ROOT, p), 'utf8'));
const evidence = read('tools/oracle/research/evidence.json');
const state = read('tools/oracle/data/state.json');
const sources = evidence.sources;
const https = (url) => /^https:\/\//.test(url);
for (const [key, s] of Object.entries(sources)) {
  if (!s.title || !s.date || !s.type || !https(s.url)) throw Error(`Invalid primary source ${key}`);
  if (!(/^(www\.sec\.gov|investor\.oracle\.com|www\.oracle\.com|openai\.com|www\.anthropic\.com)$/.test(new URL(s.url).hostname))) throw Error(`Non-primary domain: ${s.url}`);
}
for (const row of [...evidence.facts, ...evidence.sites, ...evidence.counterparties]) {
  for (const k of [row.source, row.secondary].filter(Boolean)) if (!sources[k]) throw Error(`Unknown evidence source ${k}`);
}
const relevant = (state.pending_extraction || []).filter((p) => p.status === 'pending' || p.status === 'new');
const out = { ...evidence, filingCheck: state.last_harvest || null,
  pending: relevant.map((p) => ({ form: p.form, date: p.filing_date, url: p.url, accession: p.accession })) };
const dir = join(ROOT, 'site/oracle/research/data'); mkdirSync(dir, { recursive: true });
const js = `// Reviewed source facts; generated by scripts/oracle/build-research.mjs.\nwindow.ORCL_RESEARCH = ${JSON.stringify(out)};\n`;
writeFileSync(join(dir, 'research.js'), js);
console.log(`Research evidence: ${evidence.facts.length} facts, ${evidence.sites.length} sites, ${relevant.length} pending filings.`);
